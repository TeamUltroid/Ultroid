"""Writes rust/ultroid-db/src/tables.rs from the interpreter it runs under.

    python3 rust/harness/gen_tables.py path/to/NameAliases.txt

`repr()` escapes the characters `str.isprintable()` rejects, and `\\N{...}` only knows the
characters and aliases this interpreter's Unicode database has. All of it follows the Unicode
version CPython was built with, so the port carries the same tables instead of a newer crate's.

Python cannot list its aliases, so the candidates come from Unicode's `NameAliases.txt` (any
version at least as new as the interpreter's; the `unicode_names2` crate ships one in `data/`).
Only the ones this interpreter accepts are kept.
"""

import ast
import os
import sys
import unicodedata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ultroid-db", "src", "tables.rs")


def ranges(test):
    out, start = [], None
    for code in range(0x80, 0x110000):
        hit = test(chr(code))
        if hit and start is None:
            start = code
        if not hit and start is not None:
            out.append((start, code - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, rows):
    lines = [f"/// {doc}", f"pub const {name}: [(u32, u32); {len(rows)}] = ["]
    for at in range(0, len(rows), 6):
        lines.append("    " + " ".join(f"(0x{a:x}, 0x{b:x})," for a, b in rows[at : at + 6]))
    lines.append("];")
    return "\n".join(lines)


def aliases(path):
    """Alias and code point for every alias this interpreter resolves in a string literal."""
    found = {}
    for line in open(path, encoding="utf-8"):
        fields = line.split("#")[0].strip().split(";")
        if len(fields) < 2:
            continue
        code, alias = int(fields[0], 16), fields[1]
        try:
            # Lower case on purpose: the lookup ignores case, and the table relies on that.
            hit = ast.literal_eval("'\\N{" + alias.lower() + "}'") == chr(code)
        except SyntaxError:
            hit = False
        if hit:
            found[alias.upper()] = code
    return sorted(found.items())


def alias_table(rows):
    lines = ["/// Aliases `\\N{...}` accepts besides the names, upper case and sorted, with their code points.",
             f"pub const ALIASES: [(&str, u32); {len(rows)}] = ["]
    lines += [f'    ("{alias}", 0x{code:x}),' for alias, code in rows]
    lines.append("];")
    return "\n".join(lines)


if len(sys.argv) != 2:
    sys.exit(__doc__)
version = sys.version.split()[0]
header = (
    f"//! Unicode tables of CPython {version} (Unicode {unicodedata.unidata_version}), from U+0080 up.\n"
    "//! Generated by `rust/harness/gen_tables.py`; rerun it under another interpreter to follow that one.\n"
)
body = [
    table("NONPRINTABLE", "Inclusive ranges `str.isprintable()` rejects: `repr()` escapes them.", ranges(lambda c: not c.isprintable())),
    table("UNASSIGNED", "Inclusive ranges with no assigned character (category Cn).", ranges(lambda c: unicodedata.category(c) == "Cn")),
    alias_table(aliases(sys.argv[1])),
]
with open(OUT, "w", encoding="utf-8") as out:
    out.write(header + "\n" + "\n\n".join(body) + "\n")
print(f"wrote {os.path.normpath(OUT)} for CPython {version}, Unicode {unicodedata.unidata_version}")
